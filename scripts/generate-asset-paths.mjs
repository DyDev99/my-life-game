#!/usr/bin/env node
// Regenerates src/game/assets/assetPaths.ts from the files in public/models and public/sprites.
// MODELS = 3D files, TEXTURES = images under public/models, SPRITES = images under public/sprites.
// Run after adding, removing or renaming a runtime asset:  node scripts/generate-asset-paths.mjs
import { readdirSync, writeFileSync } from "node:fs";
import { join, relative, extname, basename } from "node:path";

const root = join(import.meta.dirname, "..");
const publicDir = join(root, "public");
const outFile = join(root, "src/game/assets/assetPaths.ts");

function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? walk(join(dir, e.name)) : [join(dir, e.name)]
  );
}

function registry(subdir, exts) {
  const entries = walk(join(publicDir, subdir))
    .filter((f) => exts.includes(extname(f).toLowerCase()))
    .map((f) => [basename(f, extname(f)), "/" + relative(publicDir, f).split("\\").join("/")])
    .sort(([a], [b]) => a.localeCompare(b));
  const seen = new Set();
  for (const [key] of entries) {
    if (seen.has(key)) throw new Error(`Duplicate asset name "${key}" in public/${subdir}`);
    seen.add(key);
  }
  return entries.map(([key, url]) => `  ${key}: "${url}",`).join("\n");
}

const out = `// AUTO-GENERATED by scripts/generate-asset-paths.mjs — do not edit by hand.
// Every runtime asset URL served from public/. Reference assets through these maps
// instead of string literals so a moved or renamed file becomes a type error.

/** 3D models (FBX) in public/models, keyed by file name without extension. */
export const MODELS = {
${registry("models", [".fbx", ".glb", ".gltf"])}
} as const;

/** Textures that belong to models (public/models/**), keyed by file name without extension. */
export const TEXTURES = {
${registry("models", [".png", ".jpg", ".webp"])}
} as const;

/** 2D sprites (PNG) in public/sprites, keyed by file name without extension. */
export const SPRITES = {
${registry("sprites", [".png", ".jpg", ".webp"])}
} as const;

export type ModelName = keyof typeof MODELS;
export type TextureName = keyof typeof TEXTURES;
export type SpriteName = keyof typeof SPRITES;
`;

writeFileSync(outFile, out);
console.log(`Wrote ${relative(root, outFile)}`);
